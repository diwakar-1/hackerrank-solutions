import java.io.*;
import java.util.*;
import java.text.*;
import java.math.*;
import java.util.regex.*;

public class Solution {

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int linecount = 1;
        while(sc.hasNextLine()){
            String line = sc.nextLine();
            System.out.println(linecount+" "+line);
            linecount++;
        }
        sc.close();
    }
}
